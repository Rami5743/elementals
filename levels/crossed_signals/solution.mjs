function* ride(c, id, board, approach, from, to) {
  yield* go(c, approach);
  yield* until(c, () => Math.abs(c.ent(id).s.y - from*32) < 0.1, 0, 1800, "lift at this floor");
  yield* go(c, board);
  yield* until(c, () => Math.abs(c.bottom - to*32) < 0.1 && c.me.grounded, 0, 1800, "lift at other floor");
  yield* go(c, approach);
}
